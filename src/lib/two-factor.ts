/**
 * Shared two-factor authentication utilities
 *
 * Provides two modes for handling 2FA during login:
 *
 * 1. **Wait mode** (e.g., Caisse d'Épargne): The user approves the login
 *    externally (push notification, mobile app). The bot just waits for
 *    the page to redirect after approval.
 *
 * 2. **Code mode** (e.g., Bourse Direct): The user is prompted to enter
 *    a code (SMS or TOTP) directly in the terminal. The bot types it
 *    into the page.
 */

import readline from "readline";
import { Page } from "playwright";
import { createSpinner } from "./spinner";

/**
 * Waits for the user to approve 2FA externally (push notification, etc.)
 *
 * Shows a spinner while waiting for the page to navigate to the expected
 * URL pattern. Used when the bot has nothing to do but wait.
 *
 * @param page Playwright page instance
 * @param urlPattern Glob pattern for the expected post-login URL
 * @param options.timeout Max wait time in ms (default: 120s)
 * @param options.message Spinner message to display
 */
export async function waitForExternalApproval(
  page: Page,
  urlPattern: string,
  options?: {
    timeout?: number;
    message?: string;
  }
): Promise<void> {
  const timeout = options?.timeout ?? 120000;
  const message =
    options?.message ?? "Waiting for login (2FA may be required)...";

  const spinner = createSpinner(message);
  spinner.start();
  try {
    await page.waitForURL(urlPattern, { timeout });
    spinner.stop("✅ Login successful");
  } catch (error) {
    spinner.stop();
    throw error;
  }
}

/**
 * Prompts the user to enter a 2FA code via the terminal (stdin)
 *
 * Used when the bot needs the user to provide a code received by
 * SMS or generated by an authenticator app.
 *
 * @param message Prompt message to display
 * @param options.timeout Max wait time in ms (default: 300s / 5 minutes)
 * @returns The code entered by the user (trimmed)
 */
export function promptForCode(
  message?: string,
  options?: { timeout?: number }
): Promise<string> {
  const timeout = options?.timeout ?? 300000;
  const prompt = message ?? "🔐 Enter the 2FA code: ";

  return new Promise((resolve, reject) => {
    const rl = readline.createInterface({
      input: process.stdin,
      output: process.stdout,
    });

    const timer = setTimeout(() => {
      rl.close();
      reject(new Error("2FA code entry timed out"));
    }, timeout);

    rl.question(prompt, (answer) => {
      clearTimeout(timer);
      rl.close();
      const code = answer.trim();
      if (!code) {
        reject(new Error("No 2FA code provided"));
        return;
      }
      resolve(code);
    });
  });
}
